function decodedFile(base64: string, name: string, type: string): File {
  const bytes = Buffer.from(base64.replace(/\s/g, ''), 'base64')
  return new File([bytes], name, { type })
}

export function realDocxFile(): File {
  return decodedFile(
    DOCX_BASE64,
    'synthetic-resume.docx',
    SUPPORTED_DOCUMENT_TYPES.docx
  )
}

export function realDocFile(): File {
  return decodedFile(
    DOC_BASE64,
    'synthetic-resume.doc',
    SUPPORTED_DOCUMENT_TYPES.doc
  )
}
